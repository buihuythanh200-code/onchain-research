"""Apply hypothetical Aave V3 round-2 liquidation quotes to updated borrower balances.

Inputs: existing project CSVs generated by prepare_cascade_round2.py and
calculate_round2_rewards_pga.py. Does NOT execute an on-chain liquidation,
recalculate PGA, or apply second-round price impact.

Run:
  python execute_cascade_round2.py --self-test
  python execute_cascade_round2.py
  python execute_cascade_round2.py --mode ALL_ELIGIBLE
  python execute_cascade_round2.py --round2-mode ALL_ELIGIBLE
"""
import argparse
from collections import defaultdict
from decimal import Decimal
from pathlib import Path

from validate_liquidation_state_update import (
    D, BLOCK, EPS, FILES, load_csv, parse_shocks, calculate_hf,
    update_position, write_csv,
)
from prepare_cascade_round2 import NEEDED, classify, load_impacts

TOL = D('0.0001')


def select_pairs(rows):
    grouped = defaultdict(list)
    for row in rows:
        grouped[(row['scenario'], row['borrower_address'].lower())].append(row)
    result = {}
    for key, options in grouped.items():
        options.sort(key=lambda x: (
            -D(x['estimated_gross_profit_before_gas_swap_slippage_usd']),
            x['collateral_address'].lower(), x['debt_address'].lower()))
        result[key] = options[0]
    return result


def build_assets(rows):
    users = defaultdict(dict)
    for r in rows:
        user, address = r['borrower_address'].lower(), r['asset_address'].lower()
        if address in users[user]:
            raise ValueError(f'Duplicate user token: {user} {address}')
        users[user][address] = {
            'symbol': r['symbol'], 'reserve_id': int(r['reserve_id']),
            'emode_category': int(r['emode_category']),
            'baseline_price_usd': D(r['price_usd']),
            'collateral_amount': D(r['collateral_amount']),
            'debt_amount': D(r['debt_amount']),
            'collateral_enabled': r['collateral_enabled'].strip().lower() == 'true',
            'base_lt_bps': D(r['base_lt_bps']),
        }
    if len(users) != 530:
        raise ValueError(f'Expected 530 sampled borrowers, got {len(users)}')
    return users


def index_unique(rows, names):
    out = {}
    for row in rows:
        key = tuple(row[n].lower() if n == 'borrower_address' else row[n] for n in names)
        if key in out:
            raise ValueError(f'Duplicate record: {key}')
        out[key] = row
    return out


def assert_close(x, y, context):
    if abs(x - y) > TOL:
        raise ValueError(f'{context}: mismatch {x} vs {y}')


def run(args):
    root = args.directory
    if args.source is None:
        args.source = 'round1' if args.mode == 'PGA_SPNE' else 'sensitivity'
    tables = {k: load_csv(root / filename, NEEDED[k]) for k, filename in FILES.items()}
    users = build_assets(tables['assets'])
    emode_lt = {int(r['emode_category']): D(r['liquidation_threshold_bps']) / 10000
                for r in tables['emodes']}
    bitmaps = {int(r['emode_category']): int(r['collateral_bitmap'])
               for r in tables['mapping']}
    scenarios = {r['scenario']: parse_shocks(r['price_shocks']) for r in tables['scenarios']
                 if r['scenario'] != 'S0_BASELINE'}
    impacts = load_impacts(root, args.source, args.mode, args.players, args.liquidity)
    if set(scenarios) != set(impacts):
        raise ValueError('Scenario and impact sets mismatch')

    first_pairs = select_pairs(tables['pairs'])
    first_games = index_unique([x for x in tables['pga']
                                if int(x['num_liquidators']) == args.players],
                               ('scenario', 'borrower_address'))
    if set(first_pairs) != set(first_games):
        raise ValueError('First-round PGA/quote keys mismatch')

    suffix = f'{args.mode.lower()}_n{args.players}'
    states = index_unique(load_csv(root / f'aave_cascade_round2_state_{suffix}.csv',
                               ['scenario', 'borrower_address', 'status',
                                'hf_after_round1_and_impact', 'collateral_usd_after',
                                'debt_usd_after', 'executed_round1']),
                          ('scenario', 'borrower_address'))
    second_pairs = select_pairs(load_csv(root / f'aave_round2_reward_estimates_{suffix}.csv',
        ['scenario', 'borrower_address', 'collateral_address', 'debt_address',
         'collateral_price_after_shock_usd', 'debt_price_after_shock_usd',
         'estimated_debt_repaid_usd', 'estimated_collateral_seized_before_protocol_fee_usd',
         'estimated_protocol_fee_usd', 'estimated_collateral_received_by_liquidator_usd',
         'estimated_gross_profit_before_gas_swap_slippage_usd']))
    second_games = index_unique(load_csv(root / f'aave_round2_pga_spne_results_{suffix}.csv',
        ['scenario', 'borrower_address', 'winner', 'num_liquidators',
         'collateral_symbol', 'debt_symbol', 'estimated_debt_repaid_usd']),
        ('scenario', 'borrower_address'))
    if set(second_pairs) != set(second_games):
        raise ValueError('Second-round PGA/quote keys mismatch')

    records, summary, sales, positions = [], [], defaultdict(lambda: D(0)), []
    for scenario, base in sorted(scenarios.items()):
        price_impacts = impacts[scenario]
        effective = {sym: (1 + base.get(sym, D(0))) * (1 - price_impacts.get(sym, D(0))) - 1
                     for sym in set(base) | set(price_impacts)}
        counts = defaultdict(int)
        totals = defaultdict(lambda: D(0))
        for user, baseline in sorted(users.items()):
            key = (scenario, user)
            reference = states.get(key)
            if reference is None:
                raise ValueError(f'Missing audited round-2 state: {key}')
            pair1, game1 = first_pairs.get(key), first_games.get(key)
            executed1 = pair1 is not None and (args.mode == 'ALL_ELIGIBLE' or game1['winner'] != 'NONE')
            if str(executed1).lower() != reference['executed_round1'].lower():
                raise ValueError(f'First-round execution mismatch: {key}')
            after_first = (update_position(baseline, pair1, base)[0] if executed1
                           else {a: dict(t) for a, t in baseline.items()})
            before_hf, before_coll, before_debt = calculate_hf(after_first, effective, emode_lt, bitmaps)
            before_status = classify(before_hf, before_coll, before_debt)
            if before_status != reference['status']:
                raise ValueError(f'Pre-second-round status mismatch: {key}')
            assert_close(before_coll, D(reference['collateral_usd_after']), 'collateral pre-2')
            assert_close(before_debt, D(reference['debt_usd_after']), 'debt pre-2')
            if before_hf is None:
                if reference['hf_after_round1_and_impact'] != 'NO_DEBT':
                    raise ValueError(f'HF missing reference mismatch: {key}')
            else:
                assert_close(before_hf, D(reference['hf_after_round1_and_impact']), 'HF pre-2')
            pair2, game2 = second_pairs.get(key), second_games.get(key)
            eligible = before_status == 'ELIGIBLE_ROUND2'
            if eligible != (pair2 is not None):
                raise ValueError(f'Round-2 candidate mismatch: {key}')
            executed2 = False
            transferred = None
            after_second = after_first
            if pair2 is not None:
                if int(game2['num_liquidators']) != args.players:
                    raise ValueError('Player count mismatch')
                if pair2['collateral_symbol'] != game2['collateral_symbol'] or pair2['debt_symbol'] != game2['debt_symbol']:
                    raise ValueError('Second-round PGA pair mismatch')
                assert_close(D(pair2['estimated_debt_repaid_usd']), D(game2['estimated_debt_repaid_usd']), 'PGA debt match')
                executed2 = args.round2_mode == 'ALL_ELIGIBLE' or game2['winner'] != 'NONE'
                if executed2:
                    # update_position expects baseline prices plus shocks. For round 2,
                    # replace reference prices with current shocked/impacted prices;
                    # then pass NO extra shock, preventing double price application.
                    current = {addr: dict(token, baseline_price_usd=(token['baseline_price_usd'] *
                               (1 + effective.get(token['symbol'], D(0)))))
                               for addr, token in after_first.items()}
                    updated, transferred = update_position(current, pair2, {})
                    # Restore original historical prices: HF calculation applies the
                    # single combined shock exactly once to every reserve.
                    after_second = {addr: dict(token, baseline_price_usd=after_first[addr]['baseline_price_usd'])
                                    for addr, token in updated.items()}
                    counts['executed_round2'] += 1
                    for field, value in transferred.items():
                        if field.endswith('_usd'):
                            totals[field] += value
                    sales[(scenario, pair2['collateral_symbol'])] += transferred['liquidator_collateral_usd']
                else:
                    counts['round2_no_winner'] += 1
            after_hf, after_coll, after_debt = calculate_hf(after_second, effective, emode_lt, bitmaps)
            after_status = classify(after_hf, after_coll, after_debt)
            counts[after_status] += 1
            if eligible:
                counts['eligible_before_round2'] += 1
            if executed2:
                records.append({
                    'scenario': scenario, 'borrower_address': user, 'snapshot_block': BLOCK,
                    'first_round_mode': args.mode, 'second_round_mode': args.round2_mode,
                    'collateral_symbol': pair2['collateral_symbol'], 'debt_symbol': pair2['debt_symbol'],
                    'winner': game2['winner'], 'hf_before_round2': str(before_hf),
                    'hf_after_round2': str(after_hf) if after_hf is not None else 'NO_DEBT',
                    'debt_before_usd': str(before_debt), 'debt_after_usd': str(after_debt),
                    'collateral_before_usd': str(before_coll), 'collateral_after_usd': str(after_coll),
                    **{k: str(v) for k, v in transferred.items()},
                    'status_after_round2': after_status,
                })
            for addr, token in after_second.items():
                positions.append({
                    'scenario': scenario, 'snapshot_block': BLOCK, 'borrower_address': user,
                    'first_round_mode': args.mode, 'second_round_mode': args.round2_mode,
                    'asset_address': addr, 'symbol': token['symbol'],
                    'reserve_id': token['reserve_id'], 'emode_category': token['emode_category'],
                    'collateral_enabled': token['collateral_enabled'],
                    'base_lt_bps': str(token['base_lt_bps']),
                    'baseline_price_usd': str(token['baseline_price_usd']),
                    'current_price_usd': str(token['baseline_price_usd'] *
                                             (1 + effective.get(token['symbol'], D(0)))),
                    'collateral_amount': str(token['collateral_amount']),
                    'debt_amount': str(token['debt_amount']),
                })
        if counts['eligible_before_round2'] != sum(1 for sc, _ in second_pairs if sc == scenario):
            raise ValueError('Round-2 eligible count disagrees with quote inventory')
        if sum(counts[s] for s in ('ELIGIBLE_ROUND2', 'UNBACKED_DEBT_MODEL', 'HEALTHY', 'NO_DEBT')) != len(users):
            raise ValueError('Borrower state partition mismatch')
        summary.append({
            'scenario': scenario, 'snapshot_block': BLOCK, 'first_round_mode': args.mode,
            'second_round_mode': args.round2_mode, 'num_liquidators': args.players,
            'eligible_before_round2': counts['eligible_before_round2'],
            'executed_round2': counts['executed_round2'],
            'round2_no_winner': counts['round2_no_winner'],
            'eligible_after_round2_before_price_feedback': counts['ELIGIBLE_ROUND2'],
            'unbacked_debt_accounts': counts['UNBACKED_DEBT_MODEL'],
            'healthy_accounts': counts['HEALTHY'], 'no_debt_accounts': counts['NO_DEBT'],
            'debt_repaid_round2_usd': str(totals['debt_repaid_usd']),
            'collateral_seized_round2_usd': str(totals['collateral_seized_usd']),
            'liquidator_collateral_round2_usd': str(totals['liquidator_collateral_usd']),
            'protocol_fee_round2_usd': str(totals['protocol_fee_usd']),
        })
        print(f'{scenario}: eligible={counts["eligible_before_round2"]}, '
              f'executed={counts["executed_round2"]}, no_winner={counts["round2_no_winner"]}, '
              f'remaining_eligible={counts["ELIGIBLE_ROUND2"]}, unbacked={counts["UNBACKED_DEBT_MODEL"]}')
    tag = f'{args.mode.lower()}_then_{args.round2_mode.lower()}_n{args.players}'
    base_name = f'aave_round2_executed_{tag}'
    fields = {
        'details': (records, list(records[0]) if records else ['scenario', 'borrower_address']),
        'summary': (summary, list(summary[0])),
        'sales': ([{'scenario': sc, 'collateral_symbol': token, 'hypothetical_sale_usd': str(amount)}
                   for (sc, token), amount in sorted(sales.items())],
                  ['scenario', 'collateral_symbol', 'hypothetical_sale_usd']),
        'positions': (positions, list(positions[0])),
    }
    for kind, (rows, columns) in fields.items():
        path = root / f'{base_name}_{kind}.csv'
        write_csv(path, rows, columns)
        print('CSV:', path.name)
    print('=== HYPOTHETICAL ROUND-2 STATE UPDATE COMPLETE ===')
    print('WARNING: No second-round price impact, refreshed auction after execution, '
          'or on-chain transaction has been simulated.')


def self_test():
    from validate_liquidation_state_update import test_arithmetic
    test_arithmetic()
    baseline = {'symbol': 'C', 'baseline_price_usd': D('2'), 'collateral_amount': D(100),
                'debt_amount': D(0), 'collateral_enabled': True, 'base_lt_bps': D(8000),
                'reserve_id': 0, 'emode_category': 0}
    shock = D('-0.1')
    changed = dict(baseline, baseline_price_usd=baseline['baseline_price_usd'] * (1 + shock))
    assert changed['baseline_price_usd'] == D('1.8')
    restored = dict(changed, baseline_price_usd=baseline['baseline_price_usd'])
    assert restored['baseline_price_usd'] == D('2')
    print('ROUND-2 SELF-TEST PASS: shock prices applied once and restored')


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--directory', type=Path, default=Path('.'))
    p.add_argument('--mode', choices=('PGA_SPNE', 'ALL_ELIGIBLE'), default='PGA_SPNE',
                   help='How round 1 was assumed executed')
    p.add_argument('--round2-mode', choices=('PGA_SPNE', 'ALL_ELIGIBLE'), default='PGA_SPNE',
                   help='How to select round-2 liquidation executions')
    p.add_argument('--players', type=int, choices=(3, 5), default=3)
    p.add_argument('--liquidity', type=D, default=D('10000000'))
    p.add_argument('--source', choices=('round1', 'sensitivity'), default=None)
    p.add_argument('--self-test', action='store_true')
    args = p.parse_args()
    if args.self_test:
        self_test()
    else:
        run(args)


if __name__ == '__main__':
    main()
